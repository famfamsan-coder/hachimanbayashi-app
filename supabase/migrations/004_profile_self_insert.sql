-- ============================================================
-- profiles: 自己初期作成ポリシー
-- ------------------------------------------------------------
-- ログインしたユーザーが profiles にまだ行を持っていない場合に、
-- クライアントから「自分自身の行」だけを初期作成できるようにする。
--
-- 制約:
--   - id は必ず auth.uid() と一致（他人の行を作れない）
--   - role は 'member' 固定（昇格の抜け道にしない）
--   - 2 回目以降の INSERT は主キー重複で自然に弾かれる
--
-- 既存の "管理者プロフィール管理(insert)" ポリシーはそのまま残す。
-- ============================================================

create policy "自分のプロフィール初期作成"
  on public.profiles for insert to authenticated
  with check (id = auth.uid() and role = 'member');
